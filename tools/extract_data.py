# -*- coding: utf-8 -*-
"""Build js/data.js from the item sources of every language.

Usage: python tools/extract_data.py js/data.js
Sources: tools/make_busola_pdf.py (ro), tools/make_busola_pdf_de.py (de), tools/lang_en.py, lang_fr.py, lang_it.py.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCES = {"ro": "make_busola_pdf.py", "de": "make_busola_pdf_de.py", "en": "lang_en.py", "fr": "lang_fr.py",
           "it": "lang_it.py"}
KEYS = ["TYPE_NAME", "TYPE_DESC", "INT", "CONF", "ANCHORS", "B5", "B5_NAME", "SDT", "CTX", "ADAPT", "OPEN", "OCC",
        "SC_LIKE", "SC_CONF", "SC_TRUE", "SC_DESC", "SC_STR"]


def load(path):
    src = open(path, encoding="utf-8").read()
    ns = {}
    exec(src[src.index("TYPES = ["):src.index("n_int =")], ns)
    return {k: ns[k] for k in KEYS}


def pack(d):
    return {
        "typeName": d["TYPE_NAME"], "typeDesc": d["TYPE_DESC"],
        "int": d["INT"], "conf": d["CONF"],
        "anchors": [{"code": c, "name": n, "items": it, "desc": ds} for c, n, it, ds in d["ANCHORS"]],
        "b5": [{"trait": t, "rev": k != "+", "txt": x} for t, k, x in d["B5"]],
        "b5Name": d["B5_NAME"],
        "sdt": [{"name": n, "items": it} for n, it in d["SDT"].items()],
        "ctx": [list(p) for p in d["CTX"]],
        "adapt": [{"name": n, "items": it} for n, it in d["ADAPT"].items()],
        "open": [{"name": n, "q": q, "what": w} for n, q, w in d["OPEN"]],
        "scales": {"like": d["SC_LIKE"], "conf": d["SC_CONF"], "true": d["SC_TRUE"], "desc": d["SC_DESC"],
                   "strength": d["SC_STR"]},
    }


def shape(p):
    return ({t: len(v) for t, v in p["int"].items()}, {t: len(v) for t, v in p["conf"].items()},
            [(a["code"], len(a["items"])) for a in p["anchors"]], [(b["trait"], b["rev"]) for b in p["b5"]],
            [len(n["items"]) for n in p["sdt"]], len(p["ctx"]), [len(d["items"]) for d in p["adapt"]],
            len(p["open"]), {k: len(v) for k, v in p["scales"].items()})


raw = {lang: load(os.path.join(HERE, f)) for lang, f in SOURCES.items()}
out = {lang: pack(d) for lang, d in raw.items()}
for lang in out:
    assert shape(out[lang]) == shape(out["ro"]), lang

occ = []
for i, (ro_name, de_name, code) in enumerate(raw["ro"]["OCC"]):
    row = {"code": code, "ro": ro_name}
    for lang in ("de", "en", "fr", "it"):
        name, c = raw[lang]["OCC"][i]
        assert c == code, (lang, i, name, c, code)
        row[lang] = name
    occ.append(row)
out["occ"] = occ

js = ("// Generated by tools/extract_data.py from the item sources in tools/. Edit there, then regenerate.\n"
      "export const DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
open(sys.argv[1], "w", encoding="utf-8").write(js)
print("ok", len(js), "languages:", ", ".join(out.keys() - {"occ"}))
